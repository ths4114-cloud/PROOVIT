const TODAY_DAY = 12;

export const previewMissions: MissionDetail[] = missionContent.map((content) => {
  const { day } = content;
  const status = day < TODAY_DAY ? 'accepted' : day === TODAY_DAY ? 'available' : 'locked';
  return {
    id: `day-${day}`,
    day,
    title: content.title,
    phase: content.phase,
    status,
    availableScore: day === TODAY_DAY ? 100 : 0,
    awardedScore: day < TODAY_DAY ? 100 : null,
    opensAt: `2026-10-${String(day).padStart(2, '0')}T00:00:00+09:00`,
    proofCloseAt: '2026-11-04T00:00:00+09:00',
    description: content.description,
    steps: content.steps,
    proofGuide: content.proofGuide,
  };
});

export const todayMission = previewMissions[TODAY_DAY - 1];

export function getPreviewMission(id: string) {
  return previewMissions.find((mission) => mission.id === id);
}
